// Generates src/design/tokens.css from src/design/tokens.json (one token source).
//
//   node scripts/tokens.mjs           write the CSS (run by `npm run dev` and `npm run build` through pre-scripts)
//   node scripts/tokens.mjs --check   fail if the committed CSS differs from the JSON, or a contrast pair misses its minimum
//
// No dependencies: plain Node. The CSS has light values on :root, dark values on :root[data-theme="dark"], and a
// Tailwind `@theme inline` block so every semantic colour is also a utility (bg-card, text-lifecycle-active-foreground…).
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SOURCE = path.join(root, "src/design/tokens.json");
const TARGET = path.join(root, "src/design/tokens.css");

export function build(tokens) {
  const { primitive, color } = tokens;
  const value = (name, theme) => {
    const ref = color[name][theme];
    const hex = primitive[ref];
    if (!hex) throw new Error(`tokens.json: color.${name}.${theme} names "${ref}", which is not a primitive`);
    return hex.toLowerCase();
  };
  const names = Object.keys(color).filter((n) => !n.startsWith("$"));
  const block = (theme) => names.map((n) => `  --${n}: ${value(n, theme)};`).join("\n");
  const motion = Object.entries(tokens.motion).map(([k, v]) => `  --${k}: ${v};`).join("\n");
  const layout = Object.entries(tokens.layout ?? {}).filter(([k]) => !k.startsWith("$")).map(([k, v]) => `  --${k}: ${v};`).join("\n");
  const text = Object.entries(tokens.text).filter(([k]) => !k.startsWith("$"));
  const lines = [
    "/* Generated by scripts/tokens.mjs from tokens.json. Do not edit: change tokens.json and run `npm run tokens`. */",
    "",
    ":root {",
    "  color-scheme: light;",
    `  --radius: ${tokens.radius.radius};`,
    motion,
    layout,
    `  --font-features: ${tokens.font.features};`,
    block("light"),
    "}",
    "",
    "/* Dark: elevation by surface step (background, card, popover), not shadows; the sidebar stays ink. */",
    ':root[data-theme="dark"] {',
    "  color-scheme: dark;",
    block("dark"),
    "}",
    "",
    "/* Motion is removed for people who ask for less. */",
    "@media (prefers-reduced-motion: reduce) {",
    "  :root { --duration-fast: 0ms; --duration-base: 0ms; }",
    "}",
    "",
    "@theme inline {",
    ...names.map((n) => `  --color-${n}: var(--${n});`),
    "  --ease-standard: var(--ease);",
    "  --default-transition-duration: var(--duration-fast);",
    "  --default-transition-timing-function: var(--ease);",
    "}",
    "",
    "@theme {",
    `  --font-sans: ${tokens.font.sans};`,
    `  --font-display: ${tokens.font.display};`,
    `  --font-mono: ${tokens.font.mono};`,
    ...text.flatMap(([k, [size, lh]]) => [
      `  --text-${k}: ${size};`,
      `  --text-${k}--line-height: ${lh};`,
      ...(k === "body" ? [] : [`  --text-${k}--letter-spacing: -0.01em;`]),
    ]),
    "}",
    "",
  ];
  return lines.join("\n");
}

function luminance(hex) {
  const [r, g, b] = [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16) / 255)
    .map((c) => (c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4));
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
}

export function contrast(a, b) {
  const [hi, lo] = [luminance(a), luminance(b)].sort((x, y) => y - x);
  return (hi + 0.05) / (lo + 0.05);
}

export function contrastFailures(tokens) {
  const failures = [];
  for (const theme of ["light", "dark"]) {
    for (const [fg, bg, min, only] of tokens.contrast.pairs) {
      if (only && only !== theme) continue;
      const a = tokens.primitive[tokens.color[fg][theme]];
      const b = tokens.primitive[tokens.color[bg][theme]];
      const ratio = contrast(a, b);
      if (ratio < min) failures.push(`${theme}: ${fg} (${a}) on ${bg} (${b}) is ${ratio.toFixed(2)}:1, needs ${min}:1`);
    }
  }
  return failures;
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const tokens = JSON.parse(readFileSync(SOURCE, "utf8"));
  const css = build(tokens);
  const failures = contrastFailures(tokens);
  if (failures.length) {
    console.error(`tokens.json: ${failures.length} contrast pair(s) below the minimum:\n  ${failures.join("\n  ")}`);
    process.exit(1);
  }
  if (process.argv.includes("--check")) {
    let current = "";
    try { current = readFileSync(TARGET, "utf8").replace(/\r\n/g, "\n"); } catch { /* missing counts as stale */ }
    if (current !== css) {
      console.error("src/design/tokens.css is out of date with tokens.json. Run `npm run tokens`.");
      process.exit(1);
    }
    console.log(`tokens: CSS matches tokens.json; ${tokens.contrast.pairs.length} contrast pairs pass in light and dark.`);
  } else {
    // Leave an up-to-date file alone so a running Vite (two run side by side under Playwright) sees no change.
    let current = "";
    try { current = readFileSync(TARGET, "utf8").replace(/\r\n/g, "\n"); } catch { /* first run */ }
    if (current !== css) writeFileSync(TARGET, css);
    console.log(`tokens: src/design/tokens.css ${current === css ? "already current" : "written"} (${Object.keys(tokens.color).length} colour tokens, light and dark).`);
  }
}
